module uart_rx_parity_gen(
    input   [1  : 0]    i_mode_pdata,   //-- 'b11: 9-bit data, no parity
                                        //-- 'b10:  8-bit data, even parity
                                        //-- 'b01:  8-bit data, odd parity
                                        //-- 'b00:  8-bit data, no parity
    input   [8  : 0]    i_pdata         // parallel data
    output              o_parity        
)
// LOCAL VARIABLE HERE-------------------------------------------------------
    assign o_pdata  = (i_mode_pdata[0]) ? ~^i_pdata[7: 0] : ^i_pdata[7: 0];
//---------------------------------------------------------------------------
//---------------------------------------------------------------------------
//---------------------------------------------------------------------------
//---------------------------------------------------------------------------
endmodule
