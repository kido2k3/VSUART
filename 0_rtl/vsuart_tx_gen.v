module vsuart_tx_gen #(
)(
    input	[4  : 0]	i_tx_st,
	input				i_data,
	input				i_parity,
    output				o_tx
);
// LOCAL VARIABLE HERE-------------------------------------------------------
	wire start_bit;
	wire stop_bit;
//---------------------------------------------------------------------------
	assign start_bit = 0;
	assign stop_bit = 1;
	assign o_tx = (i_tx_st == `IDLE) ? stop_bit :
			(i_tx_st == `START_BIT) ? start_bit : 
			(i_tx_st == `DATA) ? i_data :
			(i_tx_st == `PARITY) ? i_parity : stop_bit;
//---------------------------------------------------------------------------
//---------------------------------------------------------------------------
endmodule
